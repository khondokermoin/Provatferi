/**
 * Build-time only (never shipped): regenerates the subset icon font + CSS.
 *
 * The Zircos theme ships the complete Tabler Icons set — 5,936 glyphs
 * (801 KB woff2) and 5,936 CSS classes (242 KB) — on every admin page.
 * This panel uses 82 of them. This script scans the source for the icons
 * actually referenced and emits a subset of both, cutting ~1 MB off every
 * cold page load.
 *
 * Run: node build-icon-subset.mjs
 * Then commit the generated public/brand/icons/* files.
 */
import fs from "node:fs";
import path from "node:path";
import subsetFont from "subset-font";

const ROOT = path.resolve(import.meta.dirname);
const VENDOR_CSS = path.join(ROOT, "public/zircos/css/icons.min.css");
const VENDOR_FONT = path.join(ROOT, "public/zircos/fonts/tabler-icons.woff2");
const OUT_DIR = path.join(ROOT, "public/brand/icons");

// ---- 1. which icon classes does the app actually reference? ----
// Walked in Node rather than shelled out to grep: this has to run on the
// Windows dev machine as well as any POSIX box.
const used = new Set();
const ICON_RE = /\bti-[a-z0-9-]+/g;
function scan(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) { scan(full); continue; }
    if (!/\.(blade\.php|php|css|js|mjs)$/.test(entry.name)) continue;
    const text = fs.readFileSync(full, "utf8");
    for (const match of text.matchAll(ICON_RE)) used.add(match[0]);
  }
}
for (const dir of ["resources/views", "resources/css", "public/js"]) {
  const full = path.join(ROOT, dir);
  if (fs.existsSync(full)) scan(full);
}

// ---- 2. map class -> codepoint from the vendor CSS ----
const css = fs.readFileSync(VENDOR_CSS, "utf8");
const map = {};
const re = new RegExp('\\.(ti-[a-z0-9-]+):before\\{content:"\\\\([0-9a-fA-F]+)"\\}', "g");
let m;
while ((m = re.exec(css))) map[m[1]] = m[2];

const resolved = [...used].filter((i) => map[i]).sort();
const unresolved = [...used].filter((i) => !map[i]);
if (unresolved.length) console.warn("WARNING — referenced but not in the icon font:", unresolved.join(", "));
if (!resolved.length) throw new Error("no icons resolved — the vendor CSS format must have changed");

// ---- 3. subset the font to just those glyphs ----
const chars = resolved.map((i) => String.fromCodePoint(parseInt(map[i], 16))).join("");
const subset = await subsetFont(fs.readFileSync(VENDOR_FONT), chars, { targetFormat: "woff2" });

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, "provatferi-icons.woff2"), subset);

// ---- 4. emit the matching CSS (same class names, so no markup changes) ----
const rules = resolved.map((i) => `.${i}:before{content:"\\${map[i]}"}`).join("");
const outCss = `/* Generated by build-icon-subset.mjs — do not edit by hand.
   Subset of Tabler Icons v3.31.0: ${resolved.length} of 5936 glyphs, i.e. the
   icons this panel actually renders. Regenerate after adding a new ti-* icon. */
@font-face{font-family:tabler-icons;font-style:normal;font-weight:400;font-display:swap;src:url(./provatferi-icons.woff2) format("woff2")}
.ti{font-family:tabler-icons!important;speak:none;font-style:normal;font-weight:400;font-variant:normal;text-transform:none;line-height:1;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}
${rules}
`;
fs.writeFileSync(path.join(OUT_DIR, "provatferi-icons.css"), outCss);

const before = fs.statSync(VENDOR_FONT).size + fs.statSync(VENDOR_CSS).size;
const after = subset.length + Buffer.byteLength(outCss);
console.log(`icons referenced : ${resolved.length} (of 5936 in the vendor font)`);
console.log(`font  : ${(fs.statSync(VENDOR_FONT).size / 1024).toFixed(1)} KB -> ${(subset.length / 1024).toFixed(1)} KB`);
console.log(`css   : ${(fs.statSync(VENDOR_CSS).size / 1024).toFixed(1)} KB -> ${(Buffer.byteLength(outCss) / 1024).toFixed(1)} KB`);
console.log(`saved : ${((before - after) / 1024).toFixed(1)} KB per cold page load`);
